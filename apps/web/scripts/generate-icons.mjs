#!/usr/bin/env node
// Builds src/styles/_icons.generated.scss with only the Bootstrap Icons used in src,
// so the app ships a few KB of SVG masks instead of the whole icon font and stylesheet.
// Usage: node scripts/generate-icons.mjs [--check]
import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const srcDir = path.join(root, "src");
const outFile = path.join(srcDir, "styles", "_icons.generated.scss");
const iconsDir = path.join(
  path.dirname(createRequire(import.meta.url).resolve("bootstrap-icons/package.json")),
  "icons",
);
const ICON_CLASS = /\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g;

async function sourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return sourceFiles(full);
      return /\.(tsx?|jsx?)$/.test(entry.name) ? [full] : [];
    }),
  );
  return nested.flat();
}

async function usedIcons() {
  const names = new Set();
  for (const file of await sourceFiles(srcDir)) {
    for (const [, name] of (await readFile(file, "utf8")).matchAll(ICON_CLASS)) names.add(name);
  }
  return [...names].sort();
}

function toDataUri(svg) {
  const body = svg
    .replace(/\s(width|height|class|fill)="[^"]*"/g, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim()
    .replace(/"/g, "'")
    .replace(/%/g, "%25")
    .replace(/#/g, "%23")
    .replace(/</g, "%3C")
    .replace(/>/g, "%3E");
  return `url("data:image/svg+xml,${body}")`;
}

async function render() {
  const names = await usedIcons();
  const rules = await Promise.all(
    names.map(async (name) => {
      const svg = await readFile(path.join(iconsDir, `${name}.svg`), "utf8").catch(() => {
        throw new Error(`Unknown Bootstrap icon "bi-${name}"`);
      });
      return `.bi-${name} {\n  --bi-icon: ${toDataUri(svg)};\n}\n`;
    }),
  );

  return [
    "// Generated by scripts/generate-icons.mjs. Do not edit; run `npm run icons`.",
    "",
    ".bi {",
    "  display: inline-block;",
    "  flex-shrink: 0;",
    "  width: 1em;",
    "  height: 1em;",
    "  vertical-align: -0.125em;",
    "  background-color: currentColor;",
    "  mask: var(--bi-icon) center / contain no-repeat;",
    "}",
    "",
    ...rules,
  ].join("\n");
}

const output = await render();
if (process.argv.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  if (current !== output) {
    console.error("Icon styles are out of date. Run `npm run icons -w @op/web`.");
    process.exit(1);
  }
  console.log("Icon styles are up to date.");
} else {
  await writeFile(outFile, output);
  console.log(`Wrote ${path.relative(root, outFile)}`);
}
